#!/usr/bin/env python3
"""URP SubShader を 6 つのシェーダーへ生成する。

    python Tests/CI/generate_urp_subshaders.py --repo-root .          # 書き込む
    python Tests/CI/generate_urp_subshaders.py --repo-root . --check  # 差分があれば exit 1

各シェーダーの BiRP SubShader の直前に、マーカーで囲んだ 2 つの SubShader
(URP 17.1+ 用と URP 14 〜 17.0 用) を置く。URP の無いプロジェクトでは読み飛ばされる。
パスの中身はこのスクリプトか Include/URP/*.hlsl で直す。.shader を手で直さないこと。
"""
import argparse
import io
import os
import sys

BEGIN = "// <auto-generated:natane-urp-subshaders>"
END = "// </auto-generated:natane-urp-subshaders>"
LEGACY_HEADER = "// ===== URP (Universal Render Pipeline) SubShader ====="

URP = "Packages/com.unity.render-pipelines.universal"
CORE = "Packages/com.unity.render-pipelines.core"

SHADER_DIR = "Shaders/NataneToon"

# (ファイル, Include への相対パス, 種類)
TARGETS = [
    ("NataneToonShader.shader", "Include", "opaque"),
    ("Variants/NataneToonShader_Lite.shader", "../Include", "opaque"),
    ("Variants/NataneToonShader_Cutout.shader", "../Include", "cutout"),
    ("Variants/NataneToonShader_Cutout_Lite.shader", "../Include", "cutout"),
    ("Variants/NataneToonShader_Transparent.shader", "../Include", "transparent"),
    ("Variants/NataneToonShader_Transparent_Lite.shader", "../Include", "transparent"),
]

KIND_TAGS = {
    "opaque": ("Opaque", "Geometry", "Toon"),
    "cutout": ("TransparentCutout", "AlphaTest", "ToonCutout"),
    "transparent": ("Transparent", "Transparent", "ToonTransparent"),
}

STENCIL = """Stencil
{
    Ref [_StencilRef]
    Comp [_StencilComp]
    Pass [_StencilOp]
    Fail [_StencilFail]
    ZFail [_StencilZFail]
    ReadMask [_StencilReadMask]
    WriteMask [_StencilWriteMask]
}"""

INSTANCING = """// GPU Instancing + DOTS Instancing (GPU Resident Drawer)
#pragma multi_compile_instancing
#include_with_pragmas "%s/ShaderLibrary/DOTS.hlsl\"""" % URP

INSTANCING_LAYERS = """// GPU Instancing + DOTS Instancing (GPU Resident Drawer)
#pragma multi_compile_instancing
#pragma instancing_options renderinglayer
#include_with_pragmas "%s/ShaderLibrary/DOTS.hlsl\"""" % URP


def indent(text, level):
    pad = "    " * level
    return "\n".join((pad + line) if line.strip() else "" for line in text.split("\n"))


def kind_defines(kind, unity6):
    lines = []
    if unity6:
        lines.append("#define NATANE_URP_UNITY6 1")
    if kind == "cutout":
        lines.append("#define _ALPHATEST_ON 1")
    if kind == "transparent":
        lines.append("#define NATANE_URP_TRANSPARENT 1")
    return "\n".join(lines)


def hlsl_pass(name, light_mode, state, program, comment=None):
    out = []
    if comment:
        out.append("// " + comment)
    out.append("Pass")
    out.append("{")
    out.append('    Name "%s"' % name)
    out.append('    Tags { "LightMode" = "%s" }' % light_mode)
    out.append(indent(state, 1))
    out.append("")
    out.append("    HLSLPROGRAM")
    out.append(indent(program, 1))
    out.append("    ENDHLSL")
    out.append("}")
    return "\n".join(out)


def join_blocks(*blocks):
    return "\n\n".join(b for b in blocks if b)


def forward_pass(inc, kind, unity6):
    state = "Cull [_Cull]\nZWrite [_ZWrite]\nAlphaToMask [_AlphaToMask]"
    if kind == "transparent":
        state += "\nBlend [_SrcBlend] [_DstBlend]"
    state += "\n" + STENCIL

    material = """// Material Keywords (BiRP と同一キーワード)
#pragma shader_feature_local _USE_RAMP
#pragma shader_feature_local _NORMALMAP
#pragma shader_feature_local_fragment _RIM_LIGHT
#pragma shader_feature_local_fragment _MATCAP
#pragma shader_feature_local_fragment _EMISSION"""

    if unity6:
        pipeline = """// Universal Pipeline Keywords
#pragma multi_compile _ _MAIN_LIGHT_SHADOWS _MAIN_LIGHT_SHADOWS_CASCADE _MAIN_LIGHT_SHADOWS_SCREEN
#pragma multi_compile _ _ADDITIONAL_LIGHTS_VERTEX _ADDITIONAL_LIGHTS
#pragma multi_compile _ EVALUATE_SH_MIXED EVALUATE_SH_VERTEX
#pragma multi_compile_fragment _ _ADDITIONAL_LIGHT_SHADOWS
#pragma multi_compile_fragment _ _SHADOWS_SOFT _SHADOWS_SOFT_LOW _SHADOWS_SOFT_MEDIUM _SHADOWS_SOFT_HIGH
#pragma multi_compile_fragment _ _LIGHT_COOKIES
#pragma multi_compile _ _LIGHT_LAYERS
#pragma multi_compile _ _CLUSTER_LIGHT_LOOP
#include_with_pragmas "{core}/ShaderLibrary/FoveatedRenderingKeywords.hlsl"
#include_with_pragmas "{urp}/ShaderLibrary/RenderingLayers.hlsl"

// Unity Keywords
#pragma multi_compile _ SHADOWS_SHADOWMASK
#pragma multi_compile_fragment _ LOD_FADE_CROSSFADE
#include_with_pragmas "{urp}/ShaderLibrary/Fog.hlsl"
#include_with_pragmas "{urp}/ShaderLibrary/ProbeVolumeVariants.hlsl\"""".format(core=CORE, urp=URP)
        instancing = INSTANCING_LAYERS
        target = "3.5"
        light_mode = "UniversalForwardOnly"
        comment = "Forward Pass (Deferred / Deferred+ のレンダラーでも前方描画される)"
    else:
        pipeline = """// Universal Pipeline Keywords
#pragma multi_compile _ _MAIN_LIGHT_SHADOWS _MAIN_LIGHT_SHADOWS_CASCADE _MAIN_LIGHT_SHADOWS_SCREEN
#pragma multi_compile _ _ADDITIONAL_LIGHTS_VERTEX _ADDITIONAL_LIGHTS
#pragma multi_compile_fragment _ _ADDITIONAL_LIGHT_SHADOWS
#pragma multi_compile_fragment _ _SHADOWS_SOFT _SHADOWS_SOFT_LOW _SHADOWS_SOFT_MEDIUM _SHADOWS_SOFT_HIGH
#pragma multi_compile _ _FORWARD_PLUS
#pragma multi_compile_fog"""
        instancing = INSTANCING
        target = "3.0"
        light_mode = "UniversalForward"
        comment = "Forward Pass"

    program = join_blocks(
        "#pragma target %s\n#pragma vertex NataneToonPassVertex\n#pragma fragment NataneToonPassFragment" % target,
        kind_defines(kind, unity6),
        material,
        pipeline,
        instancing,
        '#include "%s/URP/NataneToonURPInput.hlsl"\n#include "%s/URP/NataneToonURPForwardPass.hlsl"' % (inc, inc),
    )
    return hlsl_pass("ForwardLit", light_mode, state, program, comment)


def outline_pass(inc, kind, unity6):
    state = "Cull Front\nZWrite [_ZWrite]"
    if kind == "transparent":
        state += "\nBlend [_SrcBlend] [_DstBlend]"
    state += "\n" + STENCIL

    material = """// Material Keywords (BiRP と同一キーワード)
#pragma shader_feature_local _OUTLINE
#pragma shader_feature_local _OUTLINE_TEXTURE_COLOR
#pragma shader_feature_local _OUTLINE_WIDTH_MAP
#pragma shader_feature_local _OUTLINE_MULTI_COLOR
#pragma shader_feature_local _OUTLINE_MASK
#pragma shader_feature_local _SMOOTH_NORMAL"""

    if unity6:
        pipeline = """#pragma multi_compile_fragment _ LOD_FADE_CROSSFADE
#include_with_pragmas "{core}/ShaderLibrary/FoveatedRenderingKeywords.hlsl"
#include_with_pragmas "{urp}/ShaderLibrary/Fog.hlsl\"""".format(core=CORE, urp=URP)
    else:
        pipeline = "#pragma multi_compile_fog"

    program = join_blocks(
        "#pragma target %s\n#pragma vertex NataneToonOutlineVertex\n#pragma fragment NataneToonOutlineFragment"
        % ("3.5" if unity6 else "3.0"),
        kind_defines(kind, unity6),
        material,
        pipeline,
        INSTANCING,
        '#include "%s/URP/NataneToonURPInput.hlsl"\n#include "%s/URP/NataneToonURPOutlinePass.hlsl"' % (inc, inc),
    )
    return hlsl_pass("Outline", "SRPDefaultUnlit", state, program,
                     "Outline Pass (SRPDefaultUnlit: Renderer Feature なしで描かれる)")


def depth_program(inc, kind, unity6, vertex, fragment, extra, instancing):
    lod = "#pragma multi_compile_fragment _ LOD_FADE_CROSSFADE" if unity6 else ""
    return join_blocks(
        "#pragma target %s\n#pragma vertex %s\n#pragma fragment %s" % ("3.5" if unity6 else "2.0", vertex, fragment),
        kind_defines(kind, unity6),
        "\n".join(x for x in (extra, lod) if x),
        instancing,
        '#include "%s/URP/NataneToonURPInput.hlsl"\n#include "%s/URP/NataneToonURPDepthPasses.hlsl"' % (inc, inc),
    )


def shadow_caster_pass(inc, kind, unity6):
    return hlsl_pass(
        "ShadowCaster", "ShadowCaster",
        "ZWrite On\nZTest LEqual\nColorMask 0\nCull [_Cull]",
        depth_program(inc, kind, unity6, "NataneShadowCasterVertex", "NataneShadowCasterFragment",
                      "#pragma multi_compile_vertex _ _CASTING_PUNCTUAL_LIGHT_SHADOW", INSTANCING),
        "Shadow Caster Pass")


def depth_only_pass(inc, kind, unity6):
    return hlsl_pass(
        "DepthOnly", "DepthOnly",
        "ZWrite On\nColorMask R\nCull [_Cull]",
        depth_program(inc, kind, unity6, "NataneDepthOnlyVertex", "NataneDepthOnlyFragment", "", INSTANCING),
        "Depth Only Pass (深度プリパス / Depth Texture)")


def depth_normals_pass(inc, kind, unity6):
    extra = "#pragma multi_compile_fragment _ _GBUFFER_NORMALS_OCT"
    if unity6:
        extra += '\n#include_with_pragmas "%s/ShaderLibrary/RenderingLayers.hlsl"' % URP
    return hlsl_pass(
        "DepthNormalsOnly", "DepthNormalsOnly",
        "ZWrite On\nCull [_Cull]",
        depth_program(inc, kind, unity6, "NataneDepthNormalsVertex", "NataneDepthNormalsFragment", extra,
                      INSTANCING_LAYERS if unity6 else INSTANCING),
        "Depth Normals Pass (SSAO / Depth Normals Texture / Deferred の法線)")


def motion_vector_pass(inc, kind, xr):
    # vertex / fragment / instancing / foveated の pragma は ObjectMotionVectors.hlsl が持つ。
    program_lines = ["#pragma multi_compile _ LOD_FADE_CROSSFADE"]
    if xr:
        program_lines.append("#define APPLICATION_SPACE_WARP_MOTION 1")
    program = join_blocks(
        "\n".join(program_lines),
        kind_defines(kind, True),
        '#include "%s/URP/NataneToonURPInput.hlsl"\n'
        '#include_with_pragmas "%s/ShaderLibrary/ObjectMotionVectors.hlsl"' % (inc, URP),
    )
    if xr:
        state = """ColorMask RGBA
Cull [_Cull]
// オブジェクトモーションを書いたピクセルをステンシルで示す (URP の Lit と同じ)
Stencil
{
    WriteMask 1
    Ref 1
    Comp Always
    Pass Replace
}"""
        return hlsl_pass("XRMotionVectors", "XRMotionVectors", state, program,
                         "XR Motion Vectors Pass (Application SpaceWarp)")
    return hlsl_pass("MotionVectors", "MotionVectors", "ColorMask RG\nCull [_Cull]", program,
                     "Motion Vectors Pass (TAA / STP / モーションブラー)")


def subshader(inc, kind, unity6):
    render_type, queue, fallback = KIND_TAGS[kind]
    passes = [forward_pass(inc, kind, unity6), outline_pass(inc, kind, unity6)]
    if kind != "transparent":
        # 半透明は BiRP 版と同じく影・深度を書かない。
        passes += [shadow_caster_pass(inc, kind, unity6), depth_only_pass(inc, kind, unity6),
                   depth_normals_pass(inc, kind, unity6)]
        if unity6:
            passes += [motion_vector_pass(inc, kind, False), motion_vector_pass(inc, kind, True)]

    if unity6:
        header = """// ===== URP SubShader: URP 17.1+ (Unity 6.1 以降。検証は Unity 6.3 LTS / URP 17.3 以降) =====
// 対応機能は Documentation~/URP_SUPPORT.md を参照。"""
        version = "17.1.0"
    else:
        header = """// ===== URP SubShader: URP 14 〜 17.0 (Unity 2022.3 / Unity 6.0) =====
// 互換パス。URP 17.1+ では _FORWARD_PLUS の宣言だけで非推奨の警告が出るので、バージョン範囲で除外する。"""
        version = "[14.0.0,17.1.0)"

    body = join_blocks(
        'PackageRequirements\n{\n    "com.unity.render-pipelines.universal": "%s"\n}' % version,
        """Tags
{
    "RenderType" = "%s"
    "Queue" = "%s"
    "RenderPipeline" = "UniversalPipeline"
    "UniversalMaterialType" = "Lit"
    "IgnoreProjector" = "True"
    "VRCFallback" = "%s"
}""" % (render_type, queue, fallback),
        *passes)
    return header + "\nSubShader\n{\n" + indent(body, 1) + "\n}"


def generated_block(inc, kind):
    text = join_blocks(
        BEGIN + """
// Tests/CI/generate_urp_subshaders.py が生成。手で編集しないこと。
// URP の無いプロジェクト (Built-in RP / VRChat) では読み飛ばされ、下の BiRP SubShader が使われる。""",
        subshader(inc, kind, True),
        subshader(inc, kind, False),
        END)
    return indent(text, 1)


def find_line(lines, predicate, start=0):
    for i in range(start, len(lines)):
        if predicate(lines[i]):
            return i
    return -1


def apply(source, block):
    """source (LF 改行) の URP ブロックを block に置き換えた文字列を返す。"""
    lines = source.split("\n")
    block_lines = block.split("\n")

    begin = find_line(lines, lambda l: l.strip() == BEGIN)
    if begin >= 0:
        end = find_line(lines, lambda l: l.strip() == END, begin)
        if end < 0:
            raise ValueError("終了マーカーがありません")
        return "\n".join(lines[:begin] + block_lines + lines[end + 1:])

    # 初回: 手書きの URP SubShader (メインシェーダーのみ) があれば置き換える。
    legacy = find_line(lines, lambda l: l.strip() == LEGACY_HEADER)
    if legacy >= 0:
        first = find_line(lines, lambda l: l.rstrip() == "    SubShader", legacy)
        birp = find_line(lines, lambda l: l.rstrip() == "    SubShader", first + 1)
        if first < 0 or birp < 0:
            raise ValueError("手書きの URP SubShader の範囲を特定できません")
        return "\n".join(lines[:legacy] + block_lines + [""] + lines[birp:])

    birp = find_line(lines, lambda l: l.rstrip() == "    SubShader")
    if birp < 0:
        raise ValueError("SubShader が見つかりません")
    return "\n".join(lines[:birp] + block_lines + [""] + lines[birp:])


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--check", action="store_true", help="書き込まず、差分があれば exit 1")
    args = parser.parse_args()

    crlf = chr(13) + chr(10)
    stale = []
    for rel, inc, kind in TARGETS:
        path = os.path.join(args.repo_root, SHADER_DIR, rel)
        with io.open(path, encoding="utf-8", newline="") as handle:
            original = handle.read()
        uses_crlf = crlf in original
        source = original.replace(crlf, "\n")
        try:
            updated = apply(source, generated_block(inc, kind))
        except ValueError as error:
            print("ERROR: %s: %s" % (rel, error))
            return 2
        if uses_crlf:
            updated = updated.replace("\n", crlf)
        if updated == original:
            continue
        stale.append(rel)
        if not args.check:
            with io.open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(updated)

    if args.check:
        if stale:
            print("URP SubShader が生成結果と一致しません: " + ", ".join(stale))
            print("python Tests/CI/generate_urp_subshaders.py --repo-root . を実行してください。")
            return 1
        print("URP SubShader: OK (%d shaders)" % len(TARGETS))
        return 0

    print("URP SubShader: %d updated, %d unchanged" % (len(stale), len(TARGETS) - len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
